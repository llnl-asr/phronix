#!/usr/bin/env python3
"""Choose 30 of the 300 lite instances so the sample covers what varies.

    scripts/pick-30.py [--out FILE] [--readme FILE]

A 30-task probe is for finding out whether the HARNESS works across the range
of things it will meet, not for scoring a model — 30 instances cannot separate
two models at any useful confidence. So the sample is chosen for coverage, and
deterministically, so every model runs the identical list.

Three axes, in the order they matter:

* **Repository.** It is the strongest proxy for everything that varies
  operationally: how the tests are invoked (django needs `runtests.py`, the
  rest take pytest paths), how big the checkout is, how long the suite takes,
  and which conftest quirks exist. Every repository is represented, because a
  repository absent from the sample is a whole class of harness bug the probe
  cannot find. Proportional sampling would not do this: django and sympy are
  64% of the list and eight repositories have six instances or fewer.
* **Patch size**, as a difficulty proxy. `files` is always 1 — SWE-bench lite
  is single-file by construction — so the churn of the reference patch is the
  available signal. Terciles over the whole list: <=4 lines, 5-9, >=10.
* **Regression surface**, the PASS_TO_PASS count. It decides how much a wrong
  fix can break, and it is what the evaluation spends its time on: a task with
  1689 tests to keep passing exercises the runner very differently from one
  with 24.
"""
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

BENCH = Path("/p/lustre5/haridev/phronix-bench")
#: Every repository appears at least this many times.
FLOOR = 2


def churn(row):
    return len([l for l in row["patch"].splitlines()
                if l[:1] in "+-" and not l.startswith(("+++", "---"))])


def count(row, key):
    value = row[key]
    return len(json.loads(value) if isinstance(value, str) else value)


def load():
    order = [l.strip() for l in (BENCH / "lite-300.txt").read_text().splitlines()
             if l.strip() and not l.startswith("#")]
    rows = {}
    for line in (BENCH / "dataset" / "lite.jsonl").read_text().splitlines():
        row = json.loads(line)
        if row["instance_id"] in order:
            rows[row["instance_id"]] = row
    return order, rows


def choose(order, rows, total=30):
    by_repo = defaultdict(list)
    for instance in order:
        by_repo[rows[instance]["repo"].split("/")[-1]].append(instance)

    # A floor for every repository, then the rest by sqrt of size: proportional
    # would give django 11 of 30 and leave the small repositories with one
    # between them, which is the coverage this sample exists to have.
    quota = {repo: FLOOR for repo in by_repo}
    left = total - FLOOR * len(by_repo)
    weights = {repo: len(ids) ** 0.5 for repo, ids in by_repo.items()}
    scale = left / sum(weights.values())
    for repo in sorted(weights, key=lambda r: -weights[r]):
        take = min(int(round(weights[repo] * scale)), len(by_repo[repo]) - quota[repo])
        take = max(0, min(take, left))
        quota[repo] += take
        left -= take
    for repo in sorted(by_repo, key=lambda r: -len(by_repo[r])):   # rounding slack
        while left > 0 and quota[repo] < len(by_repo[repo]):
            quota[repo] += 1
            left -= 1

    # Within a repository, spread over patch size, then over regression
    # surface. Deterministic: sorted, then evenly spaced — no RNG, so the list
    # is reproducible from this file alone.
    picked = []
    for repo, ids in by_repo.items():
        ranked = sorted(ids, key=lambda i: (churn(rows[i]),
                                            count(rows[i], "PASS_TO_PASS"), i))
        want = quota[repo]
        if want >= len(ranked):
            picked += ranked
            continue
        step = (len(ranked) - 1) / max(1, want - 1) if want > 1 else 0
        picked += [ranked[int(round(k * step))] for k in range(want)]

    # Emitted in the ORIGINAL order: the list is ordered on purpose — the
    # learning arm's task N benefits from 1..N-1 — and a reordered sample is a
    # different experiment.
    chosen = set(picked)
    return [i for i in order if i in chosen]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(BENCH / "lite-30-mixed.txt"))
    ap.add_argument("--readme", default="docs/lite-30-mixed.md")
    args = ap.parse_args()

    order, rows = load()
    chosen = choose(order, rows)

    header = ("# 30 of SWE-bench lite, chosen for COVERAGE not for scoring.\n"
              "# Generated by scripts/pick-30.py — see docs/lite-30-mixed.md.\n"
              "# Order matches lite-300.txt: the learning arm's task N benefits\n"
              "# from 1..N-1, so a reordered list is a different experiment.\n")
    Path(args.out).write_text(header + "\n".join(chosen) + "\n")
    print(f"wrote {len(chosen)} instances -> {args.out}")

    # --- the README -------------------------------------------------------
    by_repo = defaultdict(list)
    for instance in chosen:
        by_repo[rows[instance]["repo"].split("/")[-1]].append(instance)
    everything = defaultdict(list)
    for instance in order:
        everything[rows[instance]["repo"].split("/")[-1]].append(instance)

    def band(value):
        return "small" if value <= 4 else ("medium" if value <= 9 else "large")

    lines = [
        "# `lite-30-mixed` — 30 instances chosen for coverage",
        "",
        "Generated by `scripts/pick-30.py`. Deterministic: no RNG, so this file",
        "and that script fully explain the list, and every model runs the same 30.",
        "",
        "## What this sample is for",
        "",
        "Finding out whether the **harness** works across the range of things it",
        "meets. It is not for scoring a model: 30 instances cannot separate two",
        "models at any useful confidence, and reading a pass rate off it would be",
        "over-claiming. The 300-task runs are for that.",
        "",
        "## How the 30 were chosen",
        "",
        "Three axes, in the order they matter.",
        "",
        "**1. Repository — every one is represented.** It is the strongest proxy",
        "for what varies operationally: how the tests are invoked (django needs",
        "`runtests.py`, the rest take pytest paths), how large the checkout is,",
        "how long the suite takes, and which conftest quirks exist. A repository",
        "absent from the sample is a whole class of harness bug the probe cannot",
        "find — which is why sampling is **not** proportional. django and sympy",
        f"are {len(everything['django']) + len(everything['sympy'])} of 300 (64%)",
        "and eight repositories have six instances or fewer; proportional",
        "sampling would give django 11 slots and leave the small repositories",
        f"sharing one. Each repository gets a floor of {FLOOR}, and the remaining",
        "slots go by the square root of repository size — enough to keep the big",
        "repositories dominant without erasing the rest.",
        "",
        "**2. Patch size, as a difficulty proxy.** `files` is always 1 (lite is",
        "single-file by construction), so the churn of the reference patch is the",
        "signal available. Bands: small `<=4` lines, medium `5-9`, large `>=10`.",
        "Within a repository the picks are spread evenly across the sorted range",
        "rather than taken from one end.",
        "",
        "**3. Regression surface** — the PASS_TO_PASS count. It decides how much",
        "a wrong fix can break, and it is where the evaluation spends its time: a",
        "task with 1689 tests to keep passing exercises the runner very",
        "differently from one with 24.",
        "",
        "## The 30",
        "",
        "| instance | repo | patch | band | F2P | P2P |",
        "|---|---|---:|---|---:|---:|",
    ]
    for instance in chosen:
        row = rows[instance]
        c = churn(row)
        lines.append(f"| `{instance}` | {row['repo'].split('/')[-1]} | {c} | "
                     f"{band(c)} | {count(row, 'FAIL_TO_PASS')} | "
                     f"{count(row, 'PASS_TO_PASS')} |")

    lines += ["", "## Coverage achieved", "",
              "| repo | in the 300 | in the 30 | patch bands covered |",
              "|---|---:|---:|---|"]
    for repo in sorted(everything, key=lambda r: -len(everything[r])):
        got = by_repo.get(repo, [])
        bands = sorted({band(churn(rows[i])) for i in got},
                       key=["small", "medium", "large"].index)
        lines.append(f"| {repo} | {len(everything[repo])} | {len(got)} | "
                     f"{', '.join(bands) or '—'} |")

    spread = [churn(rows[i]) for i in chosen]
    surface = [count(rows[i], "PASS_TO_PASS") for i in chosen]
    lines += [
        "",
        f"Patch size spans {min(spread)}–{max(spread)} lines; regression surface "
        f"spans {min(surface)}–{max(surface)} tests.",
        "",
        "## Reproducing it",
        "",
        "```bash",
        "scripts/pick-30.py            # rewrites the list and this file",
        "```",
        "",
        "The list is emitted in `lite-300.txt` order. That order is significant —",
        "the learning arm's task N benefits from tasks 1..N-1 — so a reordered",
        "sample is a different experiment, not the same one shuffled.",
    ]
    Path(args.readme).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.readme}")


if __name__ == "__main__":
    main()
