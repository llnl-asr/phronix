"""Bootstrap a project: create its layer, wire its instructions, capture its memory.

This is what turns a plain repository into one phronix works in. It is designed
to be run against *someone else's* project, so every action is additive and
reversible:

* **The project layer** (``<project>/.phronix/``) is created with its content
  directories and a short README, so a teammate who clones the repo can see what
  the directory is for without reading this source.
* **Instruction files** (``CLAUDE.md``, ``AGENTS.md``,
  ``.github/copilot-instructions.md``) get a *marked block* inserted or refreshed
  — never a wholesale overwrite. A project's own instructions are the single most
  costly file to clobber, and a marker block means the next sync updates our part
  and leaves theirs untouched.
* **Claude Code's per-project memory directory** is repointed at the project
  layer. This is the load-bearing trick for "memory travels with the repo":
  Claude natively writes memory to ``~/.claude/projects/<slug>/memory/``, which is
  invisible to git and therefore lost to everyone else. Symlinking it into
  ``.phronix/memory/`` means memories written by the harness are committed
  alongside the code they are about, with no change in how the harness behaves.
* **``.gitignore``** gains the rendered build artifacts, so the generated
  per-harness agent files do not show up as noise in every diff.

Anything that would destroy existing content reports ``conflict`` and does
nothing, rather than guessing which copy the user wanted.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Dict, List, Optional

#: Delimiters for the block we manage inside a project's instruction files.
BLOCK_START = "<!-- phronix:begin -->"
BLOCK_END = "<!-- phronix:end -->"

#: Rendered per-harness artifacts. Tracked in the YAML templates, not here.
GITIGNORE_ENTRIES = [
    "# phronix: rendered per-harness agent files (regenerated by `phronix sync agents`)",
    ".claude/agents/",
    ".opencode/agents/",
    ".github/agents/",
    ".codex/agents/",
    ".claude/skills/",
    ".opencode/skills/",
    "# phronix: bytecode from loading capabilities and verifiers (suppressed, but",
    "# a stray directory from an older version or a direct import should not be tracked)",
    ".phronix/**/__pycache__/",
]

_LAYER_README = """# .phronix — this project's shared agent knowledge

Everything in here is meant to be **committed**. It is what a teammate who
clones this repository inherits: the skills the agents have learned, the agent
definitions scoped to this project, the memories from past sessions, and any
deterministic capability (MCP tool) a session built for itself.

    skills/        one directory per skill, each with a SKILL.md
    agents/        harness-neutral agent templates (*.yaml)
    memory/        one markdown file per durable fact, indexed by MEMORY.md
    capabilities/  MCP tools authored at runtime, loaded on server start
    verifiers/     the deterministic correctors that prove the above still holds
    workspace/     permission policy and model map for this project

This layer sits ABOVE the knowledge bundled inside the phronix package, so a
skill or agent here of the same name replaces the bundled one entirely.

`verifiers/` is the part that keeps the rest trustworthy. Learning and healing are
predictions; a verifier is the fixed algorithm that says whether a prediction still
holds. Run `phronix verify coverage` to see which of this project's learning has a
corrector behind it and which is still only asserted.

Nothing here should identify a person: no usernames, no absolute home paths, no
job ids. `phronix privacy scan` checks, and the write tools redact automatically.
"""


def instructions_block() -> str:
    """The managed instruction block, for callers that render it themselves.

    The benchmark harness deploys this into a throwaway checkout rather than
    running a full bootstrap, and it must be the *same* text a real deployment
    gets — an arm evaluated against benchmark-specific instructions would be
    measuring a prompt nobody ships.
    """
    return _instructions_block()


def _instructions_block() -> str:
    """The text phronix manages inside a project's instruction files.

    Deliberately short and mostly pointers. The authoritative rules live in the
    skills, where they can be loaded a section at a time; duplicating them here
    would put the full text in front of the model on every single turn and go
    stale the first time a skill is updated.

    **Phrased as requirements, not suggestions, and that is load-bearing.** An
    earlier version opened with "Before you act, find out what the project already
    knows". Measured against a real task, the agent used zero phronix tools for a
    whole session: the tools were registered, this file was read and obeyed, and
    advisory guidance simply lost to a concrete task prompt saying "fix this bug".
    A self-learning system that only learns when the model feels inclined does not
    learn. The two calls that bracket a task are therefore stated as obligations,
    with the reason each one pays for itself.
    """
    return f"""{BLOCK_START}
## phronix

This project uses [phronix](https://github.com/hariharan-devarajan/phronix): agents
build capabilities, capabilities are wrapped in skills, and both are expected to
improve every session. Two of the calls below are required on *every* task, not
only when the task looks like it needs them.

**Required — your first action on any task**, before reading code or planning:

- `skill_search(query=...)` with a description of the task. A past session may
  have already hit this exact problem and recorded the fix. Do this even when the
  task looks unfamiliar or trivially easy — one call is cheap, and rediscovering
  a known pitfall is not. An empty result is a valid, useful answer: it means you
  are the first here, and it takes seconds.
- `memory_recall(query=...)` — durable facts, decisions and standing guidance.
- `graph_query(question=..., mode="docs")` — locate the exact section of a skill
  or a source file, then read only that. Locating costs a few hundred tokens;
  reading the file costs tens of thousands.

Never reason from priors when a skill covers the task.

**Required — before you report the task finished**, record what you learned. Do
this even if the task went smoothly; "it was straightforward once I knew X" is
exactly the X worth writing down:

- Something non-obvious broke and you fixed it → `skill_write` with
  symptom → root cause → exact fix.
- A durable fact, decision, or piece of user guidance → `memory_write`.
- A procedure you followed by hand that is deterministic → `capability_new`.
  A deterministic task described in prose is a task that will be done differently
  next time.

If you genuinely learned nothing reusable, say so explicitly in your final
message. That is a real outcome; silently skipping the step is not.

**Then prove it.** Learning and healing are *predictions*; a verifier is the
deterministic *corrector* that says whether the prediction holds — same verdict,
every run, every machine.

- `verify_run(target=...)` after every write and every fix.
- `verify_new(kind=..., target=..., claim=...)` when nothing covers it.
- `verify_coverage()` before you finish, and report what you left uncovered.

An unfalsifiable claim in a shared knowledge base is a liability: it gets trusted
long after it stops being true.

**Self-healing:** if an MCP tool is missing, wrong, or broken, fix the tool. Do
not reproduce its job by hand — a manual workaround is how drift and corruption
get introduced, and it leaves the tool broken for the next session too. Then run
the corrector: "I fixed it" is exactly the claim that comes back a week later.

**Privacy:** everything persisted here is committed and shared. No usernames, no
absolute home paths, no job ids, no hostnames. The write tools redact
automatically; `privacy_scan` verifies.
{BLOCK_END}"""


def _upsert_block(path: Path, block: str) -> str:
    """Insert or refresh the phronix block in *path*, preserving everything else."""
    text = path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""
    if BLOCK_START in text and BLOCK_END in text:
        start = text.index(BLOCK_START)
        end = text.index(BLOCK_END) + len(BLOCK_END)
        updated = text[:start] + block + text[end:]
    elif text.strip():
        updated = text.rstrip("\n") + "\n\n" + block + "\n"
    else:
        updated = block + "\n"
    if updated == text:
        return "already_current"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(updated)
    return "updated"


def claude_memory_dir(project: Path) -> Path:
    """Where Claude Code keeps this project's memory.

    The slug is the absolute project path with every ``/`` turned into ``-``,
    e.g. ``/home/x/proj`` -> ``-home-x-proj``.
    """
    slug = str(Path(project).resolve()).replace("/", "-")
    return Path.home() / ".claude" / "projects" / slug / "memory"


def _link_memory_dir(dest: Path, source: Path) -> str:
    """Point *dest* at the project layer's memory, migrating anything already there.

    Cannot simply refuse on a pre-existing directory: a session will usually have
    written memories into the harness path *before* it was ever linked, and those
    files are the entire point. They are moved into *source* — never overwriting a
    same-named file whose contents differ — before *dest* becomes a symlink. If a
    genuine content conflict remains, this reports it rather than picking a winner.
    """
    dest.parent.mkdir(parents=True, exist_ok=True)
    source.mkdir(parents=True, exist_ok=True)

    try:
        if dest.is_symlink():
            if dest.resolve() == source.resolve():
                return "already_done"
            dest.unlink()
        elif dest.is_dir():
            migrated = 0
            for item in sorted(dest.iterdir()):
                target = source / item.name
                if not target.exists():
                    item.rename(target)
                    migrated += 1
                elif item.is_file() and target.is_file() and item.read_bytes() == target.read_bytes():
                    item.unlink()  # already captured, byte-identical
            remaining = [p.name for p in dest.iterdir()]
            if remaining:
                return "conflict"
            dest.rmdir()
            dest.symlink_to(os.path.relpath(source, dest.parent), target_is_directory=True)
            return "migrated" if migrated else "installed"
        elif dest.exists():
            return "conflict"

        dest.symlink_to(os.path.relpath(source, dest.parent), target_is_directory=True)
        return "installed"
    except OSError:
        return "conflict"


def _sync_gitignore(root: Path) -> str:
    path = root / ".gitignore"
    text = path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""
    missing = [line for line in GITIGNORE_ENTRIES
               if line.startswith("#") or line not in text.split("\n")]
    # Only the comment missing means the entries are all present already.
    if all(line.startswith("#") for line in missing):
        return "already_current"
    updated = text.rstrip("\n") + ("\n\n" if text.strip() else "") + "\n".join(GITIGNORE_ENTRIES) + "\n"
    path.write_text(updated)
    return "updated"


def ensure_workspace_setup(
    target_root: Optional[Path] = None,
    force: bool = False,
    link_memory: bool = True,
) -> Dict[str, Any]:
    """Create the project layer and wire the project's instructions and memory.

    Args:
        target_root: project to bootstrap (default: detected project root, else cwd).
        force: refresh the managed instruction block even if unchanged.
        link_memory: repoint Claude Code's per-project memory at the project
            layer. Set False when the user wants harness memory kept private and
            out of version control.
    """
    from phronix.layers import CONTENT_DIRS, project_layer, project_root

    root = Path(target_root).resolve() if target_root else (project_root() or Path.cwd())
    store = root / ".phronix"
    results: Dict[str, Any] = {"status": "already_done", "target": str(root),
                               "layer": str(store), "actions": [], "conflicts": []}

    def record(what: str, status: str, detail: str = "") -> None:
        results["actions"].append({"what": what, "status": status, "detail": detail})
        if status in ("installed", "updated", "migrated"):
            results["status"] = "installed"
        elif status == "conflict":
            results["status"] = "partial"
            results["conflicts"].append(detail or what)

    for kind in CONTENT_DIRS:
        directory = store / kind
        existed = directory.is_dir()
        directory.mkdir(parents=True, exist_ok=True)
        record(f".phronix/{kind}", "already_done" if existed else "installed", str(directory))

    readme = store / "README.md"
    if force or not readme.exists():
        readme.write_text(_LAYER_README)
        record(".phronix/README.md", "installed", str(readme))
    else:
        record(".phronix/README.md", "already_done", str(readme))

    block = _instructions_block()
    for relative in ("CLAUDE.md", "AGENTS.md", ".github/copilot-instructions.md"):
        record(relative, _upsert_block(root / relative, block), str(root / relative))

    record(".gitignore", _sync_gitignore(root), str(root / ".gitignore"))

    if link_memory:
        dest = claude_memory_dir(root)
        record("claude memory link", _link_memory_dir(dest, store / "memory"), str(dest))

    layer = project_layer(root)
    results["writable"] = bool(layer and layer.writable)
    return results


def main() -> None:
    """Entry point for ``phronix-bootstrap-workspace``."""
    import argparse

    parser = argparse.ArgumentParser(
        prog="phronix-bootstrap-workspace",
        description="Create this project's .phronix layer, insert the phronix block "
                    "into its instruction files, and point Claude Code's per-project "
                    "memory at the shared, version-controlled store.",
    )
    parser.add_argument("--target", default=None,
                        help="Project root (default: detected project root, else cwd).")
    parser.add_argument("--force", action="store_true",
                        help="Refresh managed content even when unchanged.")
    parser.add_argument("--no-link-memory", action="store_true",
                        help="Leave Claude Code's per-project memory where it is "
                             "(keeps harness memory out of version control).")
    args = parser.parse_args()

    root = Path(args.target).expanduser().resolve() if args.target else None
    result = ensure_workspace_setup(root, force=args.force,
                                    link_memory=not args.no_link_memory)
    print(f"Project: {result['target']}")
    print(f"Layer:   {result['layer']}")
    for action in result["actions"]:
        marker = {"installed": "+", "updated": "~", "migrated": ">", "conflict": "!"}.get(
            action["status"], "=")
        print(f"  {marker} {action['what']:34s} {action['status']}")
    for conflict in result["conflicts"]:
        print(f"  ! left alone (would have destroyed content): {conflict}")


if __name__ == "__main__":
    main()
