"""Capabilities: the MCP tools the framework builds for itself.

This is the first tier of the build order. When a session works out how to do
something *deterministically* — a transformation, a check, a lookup with one
correct answer — writing that down as prose in a skill is the wrong home for it.
Prose gets re-interpreted every run, and re-interpretation is where drift comes
from. It should become code that runs the same way every time.

A capability is a single Python module exposing one function::

    def register(mcp):
        @mcp.tool()
        def count_todos(path: str) -> str:
            \"\"\"Count TODO markers under *path*.\"\"\"
            ...

It lives in a layer's ``capabilities/`` directory, is discovered and loaded on
MCP server start, and travels with that layer — so a capability built while
working on a project is committed with the project and works for the next person
who clones it, with no installation step.

Validation happens at *write* time, not load time (:func:`new`): a module that
fails to compile or does not define ``register`` is rejected before it is
persisted. The alternative — discovering it at the next server start — means the
authoring session ends believing it succeeded, and the failure surfaces to
somebody else with no context for it.

Loading is sandbox-free by design: a capability is code the project chose to
commit, in the same trust domain as the project's own source. The real boundary
is that capabilities come from a layer under version control, where they are
reviewable, rather than from a model's scratch space.
"""
from __future__ import annotations

import importlib.util
import os
import re
import sys
import traceback
from pathlib import Path
from typing import Any, Dict, List, Optional

#: Capabilities authored by THIS server process, name -> file.
#:
#: The MCP server is long-lived for the length of an agent's work and is the
#: same process that services `capability_new`, so a tool built during a run is
#: in memory here the moment it is written. That is what makes a from-scratch
#: run possible without giving up tool-building: the run can author and call
#: its own tools while seeing none of the ones earlier runs left on disk.
_SESSION_AUTHORED: Dict[str, str] = {}

#: Environment flag: serve only what this session authored.
#:
#: Set by the benchmark runner for `--fresh`. Deliberately an environment
#: variable rather than a tuning key — it must hold for every agent the run
#: starts, including ones that construct their own server, and it must be
#: impossible for an agent to turn off from inside.
FRESH_ENV = "PHRONIX_FRESH_CAPABILITIES"


def session_only() -> bool:
    """Is this process restricted to capabilities it authored itself?"""
    return str(os.environ.get(FRESH_ENV, "")).strip().lower() in ("1", "true", "yes")


def session_authored() -> Dict[str, str]:
    """What this process has built, name -> file. A copy; the registry is private."""
    return dict(_SESSION_AUTHORED)


def visible_files() -> Dict[str, Path]:
    """The capability modules this process may load and serve, by filename.

    Normally every layer's, which is the point of layers. Under `--fresh` it is
    CORE plus CURRENT: the framework's own bundled tools, which ship with
    phronix and know nothing about any task, and whatever this session has
    authored, which is by definition its own work. Everything else — the
    project layer a previous run wrote its probes into — is filtered out.

    That filter is what `--fresh` was always claiming. Seeding "method tools"
    by filename prefix could not deliver it: `probe_` is the prefix on both a
    generic pytest runner and a tool whose docstring is "fix itermonomials'
    total-degree bug", so a from-scratch run was inheriting one task's answer.
    """
    from phronix.layers import capability_files, which_layer

    found = capability_files()
    if not session_only():
        return found
    # Keyed by filename here and by module name in the registry — compare on
    # the stem, which is the one form both agree about.
    return {name: path for name, path in found.items()
            if Path(name).stem in _SESSION_AUTHORED
            or which_layer(path) == "bundled"}

#: What a capability module must define.
ENTRY_POINT = "register"

TEMPLATE = '''"""{description}

A phronix capability: a deterministic MCP tool authored at runtime.
Generated by capability_new; edit freely — this file is the source of truth.
"""
from __future__ import annotations


def register(mcp):
    """Register this capability's tools on the MCP server."""

    @mcp.tool()
    def {name}() -> str:
        """{description}"""
        return "not implemented yet"
'''


def _valid_name(name: str) -> bool:
    return bool(re.fullmatch(r"[a-z][a-z0-9_]*", name))


def validate(source: str, name: str) -> Optional[str]:
    """Return an error message if *source* is not a usable capability, else ``None``."""
    try:
        compile(source, f"<capability {name}>", "exec")
    except SyntaxError as exc:
        return f"syntax error at line {exc.lineno}: {exc.msg}"
    if not re.search(rf"(?m)^def\s+{ENTRY_POINT}\s*\(", source):
        return (f"a capability must define `def {ENTRY_POINT}(mcp):` at module level "
                "and register its tools inside it")
    return None


def _fingerprint(source: str) -> str:
    """What a capability DOES, ignoring how it was spelled.

    Docstrings, comments, blank lines and the tool's own name are stripped, so
    two modules that differ only in naming and prose collapse to the same
    string. That is the duplicate worth catching: the same procedure authored
    twice under different names by two passes that could not see each other.
    """
    import hashlib

    text = source
    for quote in ('"' * 3, "'" * 3):
        text = re.sub(re.escape(quote) + r"(?:.|\n)*?" + re.escape(quote), "", text)

    lines = []
    for line in text.splitlines():
        line = re.sub(r"#.*$", "", line).rstrip()
        if not line.strip():
            continue
        # The name is what differs between honest duplicates.
        line = re.sub(r"\bdef\s+\w+", "def _", line)
        lines.append(" ".join(line.split()))
    return hashlib.sha256("\n".join(lines).encode()).hexdigest()


def duplicates(source: str, name: str = "") -> List[Dict[str, str]]:
    """Existing capabilities that do the same thing as *source*.

    Solution tools are task-shaped by design — a step in one task's pipeline is
    a step in another's — so the same procedure gets authored repeatedly by
    research passes that never see each other. Each copy then has to be
    maintained, verified and chosen between, and an agent facing three tools
    with the same body and different names has been handed a decision nobody
    meant to give it.
    """
    from phronix.layers import layers

    wanted = _fingerprint(source)
    found: List[Dict[str, str]] = []
    seen = set()
    for layer in layers():
        directory = layer.dir("capabilities")
        if not directory.is_dir():
            continue
        for path in sorted(directory.glob("*.py")):
            if path.stem == name or path.stem in seen:
                continue
            try:
                other = path.read_text(errors="replace")
            except OSError:
                continue
            if _fingerprint(other) == wanted:
                seen.add(path.stem)
                found.append({"name": path.stem, "layer": layer.name,
                              "file": str(path)})
    return found


#: Where a capability that knows a particular task is filed, under the layer's
#: ``capabilities/``. Everything at the top level is a METHOD tool: it knows how
#: to run tests, walk a tree, apply a patch — a procedure, carrying nothing
#: about any one repository or fix.
#:
#: The distinction is not cosmetic. A from-scratch run should inherit the
#: method tools, because "without prior learning" is a claim about learning and
#: not a claim about shell scripting. It must NOT inherit a tool named for the
#: task it is about to be measured on: `probe_fix_max_to_sum_powers_filter`
#: applies one task's fix outright, and a run that can call it has been handed
#: the answer. A filename prefix cannot tell the two apart — both are `probe_` —
#: so the scope is recorded as the place the file is kept.
TASK_CAPABILITY_DIR = "tasks"


def task_slug(topic: str) -> str:
    """Directory name for one task's capabilities."""
    return re.sub(r"[^a-z0-9]+", "-", str(topic).lower()).strip("-") or "unknown"


def for_topic(topic: str) -> List[str]:
    """Capability names filed against *topic*, respecting `--fresh`.

    The lookup a task does before it starts: has this subject been solved
    before, by anything this run is allowed to see? Under `--fresh` that is
    only what this session authored, which is what makes a from-scratch run
    from-scratch — see :func:`visible_files`.

    Solutions live here rather than in `skills/` because the two have different
    audiences. `skills/` is the framework's own method — how to plan, how to
    explore, how to judge — and it is read by every task on every repository. A
    fix for one bug in one project is not method; it is an answer, and an
    answer belongs where it can be looked up by subject and filtered by
    provenance.
    """
    wanted = TASK_CAPABILITY_DIR + "/" + task_slug(topic)
    return sorted(
        Path(name).stem for name, path in visible_files().items()
        if wanted in path.as_posix())


def new(
    name: str,
    description: str,
    source: Optional[str] = None,
    layer: Optional[str] = None,
    overwrite: bool = False,
    topic: str = "",
) -> Dict[str, Any]:
    """Author a new capability and persist it to a layer.

    Args:
        name: snake_case module name; also the default tool name in the scaffold.
        description: one line explaining what the capability is for.
        source: the full module text. Omit to get a working scaffold to fill in.
        layer: force a target layer (default: :func:`phronix.layers.resolve_write_layer`).
        overwrite: replace an existing capability of the same name.

    The new tool is not live until the MCP server restarts — a running FastMCP
    server holds tool closures captured at registration time, so a newly written
    module cannot be spliced into it. That is reported explicitly rather than left
    for the caller to discover by calling a tool that is not there.
    """
    from phronix.layers import resolve_write_layer
    from phronix.privacy import anonymize, current_users

    if not _valid_name(name):
        return {"status": "error",
                "error": f"name {name!r} must be snake_case: lowercase, digits, underscores"}

    text = source if source is not None else TEMPLATE.format(
        name=name, description=description.replace('"', "'"))
    problem = validate(text, name)
    if problem:
        return {"status": "error", "error": problem}

    # Capabilities are committed and shared like every other artifact, and a
    # hard-coded absolute path from the authoring machine is both a leak and a
    # bug for the next person to run it.
    text = anonymize(text, extra_users=current_users())

    target = resolve_write_layer(layer)
    directory = target.dir("capabilities")
    # A tool that knows a task is filed under that task, not beside the method
    # tools. Both are served identically; the location is what lets a later
    # from-scratch run inherit the methods and none of the answers.
    if topic:
        directory = directory / TASK_CAPABILITY_DIR / task_slug(topic)
    directory.mkdir(parents=True, exist_ok=True)
    # The same procedure, already built, under another name.
    #
    # Refused rather than written: a duplicate has to be maintained, verified
    # and chosen between, and an agent facing three tools with identical bodies
    # and different names has been handed a decision nobody meant to give it.
    # The existing name comes back so the caller can just use it — which is
    # what it wanted, and cheaper than what it asked for.
    twins = duplicates(text, name)
    if twins and not overwrite:
        return {"status": "duplicate",
                "error": (f"{twins[0]['name']!r} already does this — same "
                          f"procedure, different name. Use it in your pipeline "
                          f"instead of building a second copy."),
                "existing": twins, "use": twins[0]["name"]}

    dest = directory / f"{name}.py"
    if dest.exists() and not overwrite:
        return {"status": "exists", "file": str(dest), "layer": target.name,
                "hint": "pass overwrite=True to replace it"}

    dest.write_text(text)
    # Remembered in this process, so a from-scratch run can call what it just
    # built. Written to disk as well, always: the run's own store keeps it, and
    # what a run may CARRY is a separate decision made when it ends.
    _SESSION_AUTHORED[name] = str(dest)
    try:
        from phronix.knowledge_graph import mark_dirty

        mark_dirty(f"capability_new:{name}")
    except Exception:
        pass

    return {
        "status": "ok",
        "file": str(dest),
        "layer": target.name,
        "scaffolded": source is None,
        "verification": _verification_status(name),
        "next": "restart the phronix MCP server to load this capability "
                "(a running server holds tool closures captured at registration time)",
    }


def _verification_status(name: str) -> Dict[str, Any]:
    """Whether this capability has a verifier, and what to do about it.

    A capability is the tier where an unverified claim does the most damage: it
    runs automatically, produces output other steps trust, and its failures are
    silent by construction. Best-effort so introspection can never fail a write.
    """
    try:
        from phronix.verification import covers

        names = covers("capability", name)
    except Exception:
        return {"covered": None, "note": "could not determine verifier coverage"}

    if names:
        return {
            "covered": True,
            "verifiers": names,
            "next": f"Run verify_run(target={name!r}) and confirm it passes.",
        }
    return {
        "covered": False,
        "verifiers": [],
        "next": (f"No verifier covers {name!r}. Write one with verify_new(kind='capability', "
                 f"target={name!r}, claim=...) that exercises the tool on a known input "
                 "and checks the output. A tool nothing tests will drift silently, and "
                 "everything downstream will keep trusting it."),
    }


def listing() -> List[Dict[str, Any]]:
    """Every visible capability, with its docstring summary and owning layer.

    Visible means the same set the server will actually serve — under `--fresh`,
    core plus what this session built. Listing more than that would be worse
    than useless: an agent would pick a tool by name and find it is not there.
    """
    from phronix.layers import which_layer

    out: List[Dict[str, Any]] = []
    for filename, path in sorted(visible_files().items()):
        summary = ""
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
            doc = re.match(r'\s*"""(.*?)"""', text, re.DOTALL)
            if not doc:
                # The module docstring is where a capability WRITTEN BY THE
                # TEMPLATE puts its summary, and it is not where a capability
                # written by an agent puts it: those open with `import os` and
                # document the tool function itself.
                #
                # Measured, and it cost a task: a reuse run called
                # `capability_list`, got 63 tools with `"description": ""` —
                # `apply_normpath_ignore_fix` among them, which is exactly the
                # fix it needed — and had no way to tell one name from another.
                # It solved from scratch and failed the target test.
                doc = re.search(r'\n\s+def\s+\w+\([^)]*\)[^:]*:\s*"""(.*?)"""',
                                text, re.DOTALL)
            if doc:
                # First SENTENCE, not first line: these docstrings wrap, and one
                # line of a wrapped sentence stops mid-clause.
                first = " ".join(doc.group(1).strip().split())
                head, stop, _ = first.partition(". ")
                summary = (head + "." if stop else first)[:200]
        except OSError:
            pass
        out.append({
            "name": Path(filename).stem,
            "file": str(path),
            "layer": which_layer(path),
            "description": summary,
        })
    return out


def load_all(mcp: Any) -> Dict[str, Any]:
    """Import every visible capability and register its tools on *mcp*.

    One failing capability must not take the server down with it: a broken module
    is caught, reported with its traceback, and skipped, so the other tools still
    come up. A server that refuses to start because of one bad learned tool is
    the worst possible failure mode for a self-building system — it would make
    the framework's own learning the thing that bricks it.
    """
    loaded: List[str] = []
    failed: List[Dict[str, str]] = []

    # Capabilities live inside a project's committed `.phronix/` tree, so a normal
    # import drops a `__pycache__` there — untracked churn in a directory whose
    # whole purpose is to be reviewed and committed.
    previous = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        for filename, path in sorted(visible_files().items()):
            module_name = f"phronix_capability_{Path(filename).stem}"
            try:
                spec = importlib.util.spec_from_file_location(module_name, path)
                if spec is None or spec.loader is None:
                    raise ImportError(f"cannot build an import spec for {path}")
                module = importlib.util.module_from_spec(spec)
                sys.modules[module_name] = module
                spec.loader.exec_module(module)
                register = getattr(module, ENTRY_POINT, None)
                if not callable(register):
                    raise AttributeError(f"no callable {ENTRY_POINT}(mcp)")
                register(mcp)
                loaded.append(Path(filename).stem)
            except Exception as exc:
                failed.append({
                    "name": Path(filename).stem,
                    "file": str(path),
                    "error": f"{type(exc).__name__}: {exc}",
                    "traceback": traceback.format_exc(limit=4),
                })
                sys.modules.pop(module_name, None)
    finally:
        sys.dont_write_bytecode = previous

    return {"loaded": loaded, "failed": failed}
