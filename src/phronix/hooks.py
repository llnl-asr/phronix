"""Render the prompt-injection hook for every harness that supports one.

The MCP middleware (:mod:`phronix.context_middleware`) already covers *tool*
traffic for all four harnesses, because they all talk to the same server. What
it cannot see is the user's raw prompt — that never reaches MCP. Hooks close
exactly that gap, so this module is deliberately narrow: one script, one event
per harness.

Per-harness reality, which is why this is not uniform:

* **claude** — ``.claude/settings.json`` ``hooks.UserPromptSubmit``. Whatever the
  hook prints on stdout is added to the model's context.
* **codex** — ``.codex/hooks.json`` ``UserPromptSubmit``, same shape and payload
  as Claude's. Requires the user to opt in with ``[features] codex_hooks = true``
  in their OWN ``~/.codex/config.toml``; a repo must not write there, so that is
  reported as an advisory instead.
* **opencode** — no command hooks; it has a TypeScript *plugin* API instead, and
  ``chat.message`` is the prompt-level equivalent. Plugins mutate ``output``
  (return values are discarded) and unknown hook keys are silently ignored, so
  the key name below has to match the API exactly.
* **copilot** — no hook mechanism at all. Prompt-level memory falls back to the
  instructions file; tool calls are still covered by the middleware.

The hook script itself is harness-neutral: it reads the JSON payload on stdin,
pulls ``prompt``, and prints the context block. The same file backs both Claude
and Codex, and the OpenCode plugin shells out to the same Python entry point —
so there is exactly one implementation of the retrieval logic.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, Optional

HOOK_SCRIPT_NAME = "inject_context.py"

#: The gate that refuses an edit until the task's skill has been read.
GUARD_SCRIPT_NAME = "require_skill.py"

#: Env var naming the skill an attempt must load before it may edit.
REQUIRED_SKILL_ENV = "PHRONIX_REQUIRED_SKILL"
OPENCODE_PLUGIN_NAME = "phronix-context.js"

_HOOK_SCRIPT = '''#!/usr/bin/env python3
"""Inject relevant phronix memory and standing rules at prompt submission.

Generated by phronix.hooks — edit hooks.py and run `phronix sync hooks` to
re-render. Do not edit this file directly; the next sync overwrites it.

A thin shim: Claude Code and Codex CLI both hand a JSON payload on stdin and add
whatever we print to the model's context. The real logic lives in
phronix.hook_entry so the harnesses cannot drift apart.

Never fails the turn — any error exits 0 silently.
"""
import sys

try:
    from phronix.hook_entry import run
except Exception:
    sys.exit(0)

try:
    block = run(sys.stdin.read())
except Exception:
    sys.exit(0)

if block:
    sys.stdout.write(block + "\\n")
sys.exit(0)
'''

_OPENCODE_PLUGIN = '''// Generated by phronix.hooks — edit hooks.py and run `phronix sync hooks`.
// Do not edit this file directly; the next sync overwrites it.
//
// OpenCode has no command hooks, so prompt-level memory injection goes through
// the plugin API. `chat.message` fires on each user message; hooks mutate the
// `output` object (return values are discarded) and unknown hook keys are
// silently ignored, so the key name below must match the API exactly.
//
// Tool-call context is NOT injected here — the phronix MCP server's own
// middleware already covers that uniformly for every harness.

import { spawn } from "child_process"

function inject(prompt, sessionID) {
  return new Promise((resolve) => {
    let out = ""
    let done = false
    const finish = () => { if (!done) { done = true; resolve(out.trim()) } }
    try {
      const proc = spawn("python3", ["-m", "phronix.hook_entry"], {
        stdio: ["pipe", "pipe", "ignore"],
      })
      // Never hang a user's turn on a memory lookup.
      const timer = setTimeout(() => { try { proc.kill() } catch (e) {} finish() }, 5000)
      proc.stdout.on("data", (d) => { out += d.toString() })
      proc.on("error", () => { clearTimeout(timer); finish() })
      proc.on("close", () => { clearTimeout(timer); finish() })
      proc.stdin.write(JSON.stringify({ prompt, session_id: sessionID }))
      proc.stdin.end()
    } catch (e) {
      finish()
    }
  })
}

export const PhronixContext = async ({ project, client, $, directory }) => ({
  "chat.message": async (input, output) => {
    try {
      const parts = output?.message?.parts
      if (!Array.isArray(parts)) return
      const textPart = parts.find((p) => p?.type === "text" && typeof p.text === "string")
      if (!textPart || !textPart.text.trim()) return
      const block = await inject(textPart.text, output?.message?.sessionID || "opencode")
      if (block) textPart.text = `${textPart.text}\\n\\n${block}`
    } catch (e) {
      // Injection is an enhancement; never break the turn.
    }
  },
})
'''


def hook_script_source() -> str:
    return _HOOK_SCRIPT


def opencode_plugin_source() -> str:
    return _OPENCODE_PLUGIN


def _write_if_changed(path: Path, content: str, executable: bool = False) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(errors="replace") == content:
        return "already_current"
    path.write_text(content)
    if executable:
        path.chmod(0o755)
    return "updated"


def install_hook_scripts(target_root: Path) -> Dict[str, str]:
    """Materialise the hook scripts under *target_root*.

    A hook command is a RELATIVE path resolved against the project the harness
    runs in, not against this package — so the scripts must physically exist in
    the target. Writing a settings entry that points at a missing script breaks
    every prompt, which is why the scripts are installed first and the settings
    entry is written only after the file is confirmed present.
    """
    target_root = Path(target_root)
    out: Dict[str, str] = {}
    for relative, content, executable in (
        (Path(".claude") / "hooks" / HOOK_SCRIPT_NAME, _HOOK_SCRIPT, True),
        (Path(".claude") / "hooks" / GUARD_SCRIPT_NAME, _GUARD_SCRIPT, True),
        (Path(".codex") / "hooks" / HOOK_SCRIPT_NAME, _HOOK_SCRIPT, True),
        (Path(".opencode") / "plugin" / OPENCODE_PLUGIN_NAME, _OPENCODE_PLUGIN, False),
    ):
        try:
            out[str(relative)] = _write_if_changed(
                target_root / relative, content, executable=executable)
        except OSError as exc:
            out[str(relative)] = f"error: {exc}"
    return out


def hook_script_installed(root: Path, harness: str = "claude") -> bool:
    """True when the hook script exists where *harness* will look for it."""
    sub = ".claude" if harness == "claude" else ".codex"
    return (Path(root) / sub / "hooks" / HOOK_SCRIPT_NAME).is_file()


