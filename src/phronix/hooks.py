# Entry point
# ---------------------------------------------------------------------------

def advisories() -> Dict[str, str]:
    """Things the user must do themselves, because a repo cannot do them safely."""
    return {
        "codex": ("Codex hooks are opt-in: add `[features]\\ncodex_hooks = true` to "
                  "~/.codex/config.toml. A repo must not write to your global config."),
        "copilot": ("Copilot exposes no hook mechanism; prompt-level memory relies on "
                    "copilot-instructions.md. Tool calls are still covered by the MCP "
                    "middleware."),
    }


def sync_hooks(target_root: Optional[Path] = None) -> Dict[str, Any]:
    from phronix.layers import project_root

    root = Path(target_root) if target_root else (project_root() or Path.cwd())
    results = {
        "target": str(root),
        "claude": sync_claude_hooks(root),
        "codex": sync_codex_hooks(root),
        "opencode": sync_opencode_plugin(root),
        "copilot": "not_applicable",
    }
    changed = [h for h in ("claude", "codex", "opencode") if results[h] == "updated"]
    return {
        **results,
        "changed": changed,
        "advisories": advisories(),
        "summary": (f"{len(changed)} harness hook(s) updated" if changed
                    else "all harness hooks already current"),
    }


def ensure_hooks_setup(target_root: Optional[Path] = None, force: bool = False) -> Dict[str, Any]:
    """Startup self-heal step, matching the skills/agents/permissions signatures."""
    result = sync_hooks(target_root)
    return {"status": "installed" if result["changed"] or force else "already_done", **result}


def main() -> None:
    """Entry point for ``phronix-sync-hooks``."""
    import argparse

    parser = argparse.ArgumentParser(
        prog="phronix-sync-hooks",
        description="Render the prompt-injection hooks for every harness that supports one.",
    )
    parser.add_argument("--target", default=None,
                        help="Project root (default: detected project root, else cwd).")
    args = parser.parse_args()

    root = Path(args.target).expanduser().resolve() if args.target else None
    result = sync_hooks(root)
    print(f"Target: {result['target']}")
    for harness in ("claude", "codex", "opencode", "copilot"):
        print(f"  {harness:9s} {result[harness]}")
    print(result["summary"])
    for harness, note in result["advisories"].items():
        print(f"\nNOTE ({harness}): {note}")


if __name__ == "__main__":
    main()
