"""Harness-neutral YAML agent templates and the per-harness converters.

An agent is defined ONCE, as structured YAML, with clean tags instead of any
particular harness's frontmatter dialect:

.. code-block:: yaml

    name: phronix-learner
    description: >-
      Turns what a session discovered into durable knowledge ...
    model_level: level_3        # resolved per harness via active-models.json
    effort: medium              # claude/codex hint; others ignore it
    tools:                      # neutral names; converters reshape per dialect
      - Read
      - Edit
      - mcp__phronix__skill_write
    skills:
      - phronix-self-learning
    sections:                   # the ordered prompt body
      - title: What you do
        body: |
          ...
      - include: self-learning  # shared block from common-sections.yaml

Shared prose that would otherwise be pasted into every agent (self-learning
rules, context economy, privacy, self-healing) lives once in
``common-sections.yaml`` and is pulled in with ``- include: <name>``. That is
what makes a change to a standing rule a one-file edit instead of an N-agent
edit that will be applied to N-2 of them.

Converters render each template into every harness's on-disk dialect:

============  ==============================  ==========================================
harness       output path                     frontmatter dialect
============  ==============================  ==========================================
claude        .claude/agents/<name>.md        model: <class>; tools: comma string
opencode      .opencode/agents/<name>.md      mode: primary|subagent; model: provider/id;
                                              permission: {"*": deny, <tool>: allow}
copilot       .github/agents/<name>.agent.md  tools: YAML list; mcp as server/tool
codex         .codex/agents/<name>.toml       TOML: developer_instructions, model,
                                              model_reasoning_effort, sandbox_mode
============  ==============================  ==========================================

Rendered files are build artifacts: gitignored, stamped with a generation
marker, regenerated by ``ensure_agents_setup`` and the ``agents_sync`` MCP tool.
Never edit one — edit the YAML template and re-sync, or the next sync silently
reverts your change.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

HARNESSES = ("claude", "opencode", "copilot", "codex")

#: The MCP server name agents address tools through (``mcp__phronix__<tool>``).
MCP_SERVER_NAME = "phronix"

GEN_MARKER_FMT = (
    "# generated-by: phronix ({harness}) — edit the YAML template under "
    ".phronix/agents/, not this file; then run `phronix sync agents`"
)

#: Where each harness discovers agents, relative to the workspace root, and the
#: filename pattern it requires.
HARNESS_OUTPUT = {
    "claude": (".claude/agents", "{name}.md"),
    "opencode": (".opencode/agents", "{name}.md"),
    "copilot": (".github/agents", "{name}.agent.md"),
    "codex": (".codex/agents", "{name}.toml"),
}

# Built-in tool-name mapping per harness. Claude's names are the neutral form,
# since that is the vocabulary the templates are written in. MCP tools use the
# neutral ``mcp__<server>__<tool>`` spelling and are reshaped per harness.
_OPENCODE_BUILTIN = {
    "Read": "read", "Write": "write", "Edit": "edit", "Bash": "bash",
    "Grep": "grep", "Glob": "glob", "WebFetch": "webfetch", "Task": "task",
    "TodoWrite": "todowrite",
}
_COPILOT_BUILTIN = {
    "Read": "read", "Write": "edit", "Edit": "edit", "Bash": "shell",
    "Grep": "search", "Glob": "search", "WebFetch": "fetch",
}

_MCP_RE = re.compile(r"^mcp__([^_]+(?:_[^_]+)*?)__(.+)$")


class TemplateError(ValueError):
    """A YAML agent template is malformed."""


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------

def load_common_sections() -> Dict[str, Dict[str, str]]:
    """Merge every layer's shared-section library: ``{name: {title, body}}``.

    Merged key-by-key rather than whole-file, so a project can add or override
    ONE standing rule without restating the bundled library — the opposite of
    the wholesale-shadowing rule used for skills and agents, and deliberately
    so: this file is a library of independent entries, not a single document.
    """
    from phronix.layers import common_sections_files

    out: Dict[str, Dict[str, str]] = {}
    for path in common_sections_files():
        data = yaml.safe_load(path.read_text()) or {}
        sections = data.get("sections", {})
        if not isinstance(sections, dict):
            raise TemplateError(f"{path}: top-level 'sections' must be a map")
        for name, entry in sections.items():
            if not isinstance(entry, dict) or "body" not in entry:
                raise TemplateError(f"{path}: section '{name}' must be a map with a 'body'")
            out[str(name)] = {
                "title": str(entry.get("title", name)),
                "body": str(entry["body"]),
            }
    return out


def load_template(path: Path, common: Optional[Dict[str, Dict[str, str]]] = None) -> Dict[str, Any]:
    """Load and validate one agent template, resolving ``include:`` sections.

    Returns the template with ``sections`` normalized to a list of
    ``{title, body}`` dicts, includes expanded and order preserved.
    """
    data = yaml.safe_load(path.read_text())
    if not isinstance(data, dict):
        raise TemplateError(f"{path}: template must be a YAML map")
    for key in ("name", "description", "model_level", "sections"):
        if key not in data:
            raise TemplateError(f"{path}: missing required key '{key}'")
    if not re.fullmatch(r"level_[0-9]+", str(data["model_level"])):
        raise TemplateError(
            f"{path}: model_level must look like level_N, got {data['model_level']!r}")
    for key in ("tools", "skills"):
        value = data.get(key, [])
        if not isinstance(value, list) or not all(isinstance(t, str) for t in value):
            raise TemplateError(f"{path}: '{key}' must be a list of strings")

    if common is None:
        common = load_common_sections()
    resolved: List[Dict[str, str]] = []
    for i, entry in enumerate(data["sections"]):
        if not isinstance(entry, dict):
            raise TemplateError(f"{path}: sections[{i}] must be a map")
        if "include" in entry:
            name = str(entry["include"])
            if name not in common:
                raise TemplateError(
                    f"{path}: sections[{i}] includes unknown common section '{name}' "
                    f"(known: {', '.join(sorted(common))})")
            resolved.append(dict(common[name]))
        elif "body" in entry:
            resolved.append({"title": str(entry.get("title", "")), "body": str(entry["body"])})
        else:
            raise TemplateError(f"{path}: sections[{i}] needs either 'include' or 'title'+'body'")
    data["sections"] = resolved
    return data


def load_all_templates() -> List[Dict[str, Any]]:
    """Every visible agent template, merged across layers."""
    from phronix.layers import agent_templates

    common = load_common_sections()
    return [load_template(path, common) for _, path in sorted(agent_templates().items())]


