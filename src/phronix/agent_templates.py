# Model resolution per harness
# ---------------------------------------------------------------------------

#: OpenCode wants "provider/model-id"; map our provider names to its prefixes.
_OPENCODE_PROVIDER_PREFIX = {
    "ollama": "ollama",
    "claude": "anthropic",
    "copilot": "github-copilot",
    "openai": "openai",
}


def resolve_harness_models(target_root: Optional[Path] = None) -> Dict[str, Dict[str, str]]:
    """Return ``{harness: {level_N: model-string-in-that-harness's-dialect}}``.

    claude gets a model CLASS (haiku/sonnet/opus) rather than a pinned id: Claude
    Code accepts class aliases, and using them keeps rendered files stable across
    model releases instead of churning every agent file on each new id.
    """
    from phronix.harness_models import LEVELS, load_active_config, resolve_models

    config = load_active_config(target_root=target_root)
    resolved = resolve_models(config, target_root=target_root)
    out: Dict[str, Dict[str, str]] = {}

    claude_cfg = config.get("harnesses", {}).get("claude", {})
    class_by_level = claude_cfg.get("class_by_level", {}) if isinstance(claude_cfg, dict) else {}
    fallback = {"level_1": "haiku", "level_2": "sonnet", "level_3": "sonnet", "level_4": "opus"}
    out["claude"] = {
        level: str(class_by_level.get(level) or fallback[level]) for level in LEVELS
    }

    opencode = resolved.get("opencode", {})
    provider = str(opencode.get("provider", "ollama"))
    prefix = _OPENCODE_PROVIDER_PREFIX.get(provider, provider)
    out["opencode"] = {level: f"{prefix}/{opencode.get(level, 'UNRESOLVED')}" for level in LEVELS}

    for harness in ("copilot", "codex"):
        values = resolved.get(harness, {})
        out[harness] = {level: str(values.get(level, "UNRESOLVED")) for level in LEVELS}
    return out


# ---------------------------------------------------------------------------
# Rendering helpers
# ---------------------------------------------------------------------------

def _body_markdown(template: Dict[str, Any]) -> str:
    parts = []
    for section in template["sections"]:
        title, body = section["title"], section["body"].rstrip("\n")
        parts.append(f"## {title}\n\n{body}" if title else body)
    return "\n\n".join(parts) + "\n"


def _frontmatter(fields: Dict[str, Any], harness: str) -> str:
    text = yaml.safe_dump(fields, sort_keys=False, allow_unicode=True, width=100)
    return f"---\n{GEN_MARKER_FMT.format(harness=harness)}\n{text}---\n\n"


def _skill_preamble(template: Dict[str, Any]) -> str:
    """A locate-first skills instruction for harnesses with no ``skills:`` key.

    Claude Code takes a ``skills:`` frontmatter field and handles loading itself.
    The other three do not, so their rendered agents get this instead — and it
    says *locate the section you need*, not *load all your skills*, because a
    blanket load of several large skills costs exactly what the context-economy
    rule exists to avoid.
    """
    skills = template.get("skills") or []
    if not skills:
        return ""
    joined = ", ".join(skills)
    return (
        "## Locate your skills via the graph first (MANDATORY)\n\n"
        f"Your skills are: {joined}. Before anything else, for the SPECIFIC rule or "
        "section you need, query the graph rather than loading a whole skill:\n\n"
        "```\n"
        'graph_query(mode="docs", question="<topic within one of your skills>")  # -> file:line\n'
        "```\n\n"
        "Then open only that file:line range with `skill_load(name=..., section=...)`. "
        "Load a whole `SKILL.md` only when you genuinely need every part of it — an "
        "exhaustive checklist walk, for instance.\n\n"
    )


# ---------------------------------------------------------------------------
# Converters — one per harness
# ---------------------------------------------------------------------------

def render_claude(template: Dict[str, Any], level_models: Dict[str, str]) -> str:
    fields: Dict[str, Any] = {
        "name": template["name"],
        "description": template["description"],
        "model": level_models.get(template["model_level"], "sonnet"),
        "model_level": template["model_level"],
    }
    for key in ("effort", "isolation"):
        if template.get(key):
            fields[key] = template[key]
    if template.get("tools"):
        fields["tools"] = ", ".join(template["tools"])
    if template.get("skills"):
        fields["skills"] = ", ".join(template["skills"])
    return _frontmatter(fields, "claude") + _body_markdown(template)


def _opencode_tool_name(tool: str) -> str:
    match = _MCP_RE.match(tool)
    if match:
        return f"{match.group(1)}_{match.group(2)}"  # mcp__phronix__skill_load -> phronix_skill_load
    return _OPENCODE_BUILTIN.get(tool, tool.lower())


def render_opencode(template: Dict[str, Any], level_models: Dict[str, str]) -> str:
    """OpenCode's dialect: markdown with frontmatter, permissions not tools.

    ``mode`` is declared by the template rather than fixed here. OpenCode
    distinguishes a *primary* agent — one that can be asked for by name with
    ``--agent`` — from a *subagent*, which can only be delegated to. Rendering
    everything as a subagent made the name unusable:

        agent "phronix-healer" is a subagent, not a primary agent.
        Falling back to default agent

    That warning goes to stderr and the run continues, so every invocation
    silently got the default agent instead of the one it asked for — with none
    of the tool scoping the template describes. It is a configuration error that
    presents as an agent ignoring its instructions.
    """
    fields: Dict[str, Any] = {
        "description": template["description"],
        # Default subagent: most agents are delegated to, and a primary agent
        # that nothing invokes by name is only clutter in the picker.
        "mode": str(template.get("mode") or "subagent"),
        "model": level_models.get(template["model_level"], "UNRESOLVED"),
    }
    if template.get("tools"):
        # Allowlist semantics: deny everything, then allow the listed tools.
        # OpenCode uses "permission" (not "tools") with allow/deny strings.
        permission: Dict[str, str] = {"*": "deny"}
        for tool in template["tools"]:
            permission[_opencode_tool_name(tool)] = "allow"
        fields["permission"] = permission
    return _frontmatter(fields, "opencode") + _skill_preamble(template) + _body_markdown(template)


def _copilot_tool_name(tool: str) -> str:
    match = _MCP_RE.match(tool)
    if match:
        return f"{match.group(1)}/{match.group(2)}"  # mcp__phronix__skill_load -> phronix/skill_load
    return _COPILOT_BUILTIN.get(tool, tool.lower())


def render_copilot(template: Dict[str, Any], level_models: Dict[str, str]) -> str:
    fields: Dict[str, Any] = {
        "name": template["name"],
        "description": template["description"],
    }
    model = level_models.get(template["model_level"])
    if model and model != "UNRESOLVED":
        fields["model"] = model
    if template.get("tools"):
        seen: List[str] = []
        for tool in template["tools"]:
            mapped = _copilot_tool_name(tool)
            if mapped not in seen:
                seen.append(mapped)
        fields["tools"] = seen
    return _frontmatter(fields, "copilot") + _skill_preamble(template) + _body_markdown(template)


def _toml_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def _toml_multiline(value: str) -> str:
    """Render *value* as a TOML basic multi-line string (``\"\"\"...\"\"\"``).

    A TOML *literal* string (``'''...'''``) has no escape mechanism at all, so a
    literal ``'''`` anywhere in a generated markdown body would be unrecoverable.
    A basic string can represent anything as long as every backslash and quote is
    escaped — backslashes FIRST, so quote-escaping is not itself re-escaped. That
    is more escaping than the spec strictly requires, and always correct.
    """
    body = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"""\n{body}"""'


def _toml_dump(fields: Dict[str, Any]) -> str:
    """A minimal TOML writer: flat scalars, string lists, one level of tables.

    Sufficient for the agent files rendered here and nothing more — not a
    general-purpose TOML serializer.
    """
    lines: List[str] = []
    tables: List[tuple] = []
    for key, value in fields.items():
        if isinstance(value, dict):
            tables.append((key, value))
        elif isinstance(value, list):
            items = ", ".join(f'"{_toml_escape(str(v))}"' for v in value)
            lines.append(f"{key} = [{items}]")
        elif key == "developer_instructions":
            lines.append(f"{key} = {_toml_multiline(str(value))}")
        else:
            lines.append(f'{key} = "{_toml_escape(str(value))}"')
    for name, table in tables:
        lines.append(f"\n[{name}]")
        for key, value in table.items():
            lines.append(f'{key} = "{_toml_escape(str(value))}"')
    return "\n".join(lines) + "\n"


def render_codex(template: Dict[str, Any], level_models: Dict[str, str]) -> str:
    """Codex CLI subagent: TOML, not markdown + frontmatter.

    ``template['tools']`` is deliberately not rendered. Codex has no per-tool
    allow/deny concept — the equivalent is ``sandbox_mode`` + ``approval_policy``,
    neither of which Codex will accept from a repo-tracked file (an
    anti-supply-chain measure). Emitting a ``tools`` key would look like a
    permission boundary that does not exist.
    """
    body = _skill_preamble(template) + _body_markdown(template)
    fields: Dict[str, Any] = {
        "name": template["name"],
        "description": template["description"],
        "developer_instructions": body,
        "model": level_models.get(template["model_level"], "UNRESOLVED"),
    }
    if template.get("effort"):
        fields["model_reasoning_effort"] = template["effort"]
    fields["sandbox_mode"] = "workspace-write"
    return f"{GEN_MARKER_FMT.format(harness='codex')}\n\n" + _toml_dump(fields)


RENDERERS = {
    "claude": render_claude,
    "opencode": render_opencode,
    "copilot": render_copilot,
    "codex": render_codex,
}


def render_all(
    target_root: Optional[Path] = None,
    harnesses: Optional[List[str]] = None,
) -> Dict[str, Dict[str, str]]:
    """Render every visible template for every harness.

    Returns ``{harness: {relative_output_path: content}}`` and writes nothing —
    the filesystem side belongs to :mod:`phronix.agents`, so rendering stays
    pure and testable.
    """
    templates = load_all_templates()
    models = resolve_harness_models(target_root)
    out: Dict[str, Dict[str, str]] = {}
    for harness in harnesses or list(HARNESSES):
        subdir, pattern = HARNESS_OUTPUT[harness]
        renderer = RENDERERS[harness]
        files: Dict[str, str] = {}
        for template in templates:
            rel = f"{subdir}/{pattern.format(name=template['name'])}"
            files[rel] = renderer(template, models[harness])
        out[harness] = files
    return out
