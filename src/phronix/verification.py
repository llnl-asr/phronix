def covers(kind: str, target: str) -> List[str]:
    """The AUTHORED verifier names attached to one artifact.

    Built-in correctors are not listed: they cover everything by construction, so
    including them would make coverage always 100% and hide the number that
    matters — how much of the knowledge base has its *claims* checked, not just
    its structure.
    """
    return [entry["name"] for entry in discover()
            if entry.get("kind") == kind and entry.get("target") == target]


def coverage() -> Dict[str, Any]:
    """Report which learning has an authored corrector behind it, and which does not.

    Every artifact has structural correction automatically. This reports the other
    layer: how many make a claim that something can falsify. A knowledge base with
    a hundred lessons and six verifiers holds ninety-four unfalsifiable claims
    wearing the appearance of authority, and that gap is invisible unless something
    reports it.

    Memory is excluded: a memory records a decision or a piece of state, not a
    claim about the world that code can falsify.
    """
    from phronix.capabilities import listing as capability_listing
    from phronix.layers import agent_templates, which_layer
    from phronix.skills import iter_skills

    verifiers = discover()
    by_target: Dict[str, List[str]] = {}
    for entry in verifiers:
        if entry.get("target"):
            by_target.setdefault(f"{entry.get('kind')}:{entry['target']}", []).append(entry["name"])

    recent = last_results()
    artifacts: List[Dict[str, Any]] = []
    artifacts += [{"kind": "skill", "name": s["name"], "layer": s["layer"]}
                  for s in iter_skills()]
    artifacts += [{"kind": "capability", "name": c["name"], "layer": c["layer"]}
                  for c in capability_listing()]
    artifacts += [{"kind": "agent", "name": Path(f).stem, "layer": which_layer(p)}
                  for f, p in sorted(agent_templates().items())]

    covered, uncovered = [], []
    for artifact in artifacts:
        names = by_target.get(f"{artifact['kind']}:{artifact['name']}", [])
        builtin_key = f"builtin:{artifact['kind']}:{artifact['name']}"
        entry = {**artifact,
                 "builtin_last": recent.get(builtin_key, {}).get("status", "never_run")}
        if names:
            covered.append({**entry, "verifiers": names,
                            "last": [recent.get(n, {}).get("status", "never_run")
                                     for n in names]})
        else:
            uncovered.append(entry)

    orphans = [
        entry["name"] for entry in verifiers
        if entry.get("target") and not any(
            a["kind"] == entry.get("kind") and a["name"] == entry["target"] for a in artifacts)
    ]

    total = len(artifacts)
    return {
        "status": "ok",
        "total_artifacts": total,
        "structurally_corrected": total,  # built-in correctors cover everything
        "claim_verified": len(covered),
        "covered": len(covered),
        "uncovered": len(uncovered),
        "percent": round(100.0 * len(covered) / total, 1) if total else 0.0,
        "covered_detail": covered,
        "uncovered_detail": uncovered,
        # A verifier whose target no longer exists is dead weight that still
        # counts as "a verifier" to anyone skimming the directory.
        "orphaned_verifiers": orphans,
        "broken_verifiers": [e["name"] for e in verifiers
                             if e.get("error") or e.get("spec_problems")],
        "never_run": [e["name"] for e in verifiers if e["name"] not in recent],
    }
