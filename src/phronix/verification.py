"""Verification: the corrector half of the predictor/corrector pair.

Every act of learning and every act of healing is a **predictor**. An agent
observes a session and predicts: this is the root cause, this fix works, this tool
behaves correctly, this agent should now do X. Predictions are useful, and
individually unreliable — a model that is right most of the time still writes a
confidently wrong lesson often enough to poison a shared knowledge base.

A **corrector** is the deterministic counterpart: given the artifact the predictor
produced, it answers by a fixed algorithm — no model in the loop — whether the
thing is correct. Same input, same verdict, every time, on every machine. It is
the anchor that keeps the system honest while it is changing itself.

Two layers of corrector, and both always run:

**Built-in structural correctors** (:mod:`phronix.correctors`) apply to every
skill, capability and agent with no authoring required. They check the class of
error that is most common and most mechanically detectable: frontmatter parses,
names match, includes resolve, the module compiles and registers documented tools,
the template renders for all four harnesses, nothing identifies a person. Coverage
here is total by construction, because a verified fraction that starts at zero
stays at zero.

**Authored verifiers** check the *claim about the world* that structure cannot
settle — "this flag fixes that error" is not decidable from the text.

The verifier specification
--------------------------

An authored verifier is not a pass/fail function. It is a structured spec with
five facets, each individually checked and individually reported, because "it
failed" is not an actionable answer and "it passed" is not a trustworthy one:

============  ================================================================
assumptions   Preconditions the claim presumes. A failed assumption means the
              check could not run here — ``inconclusive``, never ``fail``.
inputs        What the check operates on, and whether each resolves. An
              unresolvable required input is also ``inconclusive``.
constraints   The substantive conditions the claim asserts. These are what
              ``fail`` means.
invariants    What must hold BEFORE and AFTER. Checked twice and compared; a
              violation is the most serious result, because it means running
              the check changed something it should not have.
outputs       What must be produced, and its shape. Failure is ``fail``.
============  ================================================================

Separating assumptions from constraints is what makes the signal survive. Collapse
them and every machine missing a dependency reports red, everyone learns to ignore
the wall of red, and the genuine failures go with it.
"""
