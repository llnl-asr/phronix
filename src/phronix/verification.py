def discover() -> List[Dict[str, Any]]:
    """Every visible verifier with its spec summary and owning layer.

    A module that fails to import, or whose spec is malformed, is reported WITH
    the problem rather than dropped. A verifier that silently disappears looks
    exactly like coverage that was never written — the opposite of what a broken
    check should signal.
    """
    from phronix.layers import verifier_files, which_layer

    out: List[Dict[str, Any]] = []
    for filename, path in sorted(verifier_files().items()):
        entry: Dict[str, Any] = {
            "name": Path(filename).stem,
            "file": str(path),
            "layer": which_layer(path),
        }
        try:
            module = _load_module(path)
            spec = getattr(module, SPEC_ATTR, None)
            problems = validate_spec(spec)
            spec = spec if isinstance(spec, dict) else {}
            entry.update({
                "kind": str(spec.get("kind", "")),
                "target": str(spec.get("target", "")),
                "claim": str(spec.get("claim", "")),
                "facet_counts": {f: len(spec.get(f) or []) for f in FACETS},
                "has_verify_fn": callable(getattr(module, ENTRY_POINT, None)),
            })
            if problems:
                entry["spec_problems"] = problems
        except Exception as exc:
            entry["error"] = f"{type(exc).__name__}: {exc}"
        out.append(entry)
    return out


# ---------------------------------------------------------------------------
# Evaluating one facet entry
# ---------------------------------------------------------------------------

def _normalise(raw: Any) -> Tuple[bool, str]:
    """Coerce a check's return value into ``(ok, evidence)``.

    Three accepted shapes because forcing one would add boilerplate to the common
    case (a bare comparison) without adding information.
    """
    if isinstance(raw, dict):
        return bool(raw.get("ok")), str(raw.get("evidence", ""))
    if isinstance(raw, tuple) and len(raw) == 2:
        return bool(raw[0]), str(raw[1])
    return bool(raw), ""


def _run_check(entry: Dict[str, Any], key: str, ctx: Dict[str, Any]) -> Dict[str, Any]:
    """Evaluate one facet entry, never raising."""
    result = {"name": str(entry.get("name", "?")), "detail": str(entry.get("detail", ""))}
    try:
        raw = entry[key](ctx)
    except Exception as exc:
        return {**result, "ok": False, "errored": True,
                "evidence": f"{type(exc).__name__}: {exc}"}
    ok, evidence = _normalise(raw)
    return {**result, "ok": ok, "evidence": evidence}


