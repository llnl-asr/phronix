def new(
    name: str,
    kind: str,
    target: str,
    claim: str,
    source: Optional[str] = None,
    layer: Optional[str] = None,
    overwrite: bool = False,
) -> Dict[str, Any]:
    """Author a verifier and persist it beside the learning it corrects."""
    from phronix.layers import resolve_write_layer
    from phronix.privacy import anonymize, current_users

    if not _valid_name(name):
        return {"status": "error",
                "error": f"name {name!r} must be snake_case: lowercase, digits, underscores"}
    if kind not in VERIFIABLE_KINDS:
        return {"status": "error",
                "error": f"kind={kind!r} must be one of {'|'.join(VERIFIABLE_KINDS)}"}
    if not claim.strip():
        return {"status": "error",
                "error": "claim is required: a verifier with no stated claim cannot be "
                         "reviewed, and nobody can tell later what a failure means"}

    text = source if source is not None else TEMPLATE.format(
        description=f"Verifies: {claim}".replace('"', "'"),
        kind=kind, target=target, claim=claim.replace('"', "'").replace("\n", " "),
    )
    problem = validate(text, name)
    if problem:
        return {"status": "error", "error": problem}

    text = anonymize(text, extra_users=current_users())

    write_layer = resolve_write_layer(layer)
    directory = write_layer.dir("verifiers")
    directory.mkdir(parents=True, exist_ok=True)
    dest = directory / f"{name}.py"
    if dest.exists() and not overwrite:
        return {"status": "exists", "file": str(dest), "layer": write_layer.name,
                "hint": "pass overwrite=True to replace it"}

    dest.write_text(text)
    try:
        from phronix.knowledge_graph import mark_dirty

        mark_dirty(f"verifier_new:{name}")
    except Exception:
        pass

    return {
        "status": "ok",
        "file": str(dest),
        "layer": write_layer.name,
        "verifies": {"kind": kind, "target": target, "claim": claim},
        "scaffolded": source is None,
        "facets": list(FACETS),
        "next": ("Fill in the SPEC facets — a scaffold has no constraints and therefore "
                 "cannot fail, which means it proves nothing. Then run "
                 f"verify_run(name={name!r}) and confirm every facet passes."
                 if source is None else
                 f"Run verify_run(name={name!r}) now. A verifier that has never been "
                 "executed is not evidence."),
    }


