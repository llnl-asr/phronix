#: What a verifier module must define.
SPEC_ATTR = "SPEC"
ENTRY_POINT = "verify"

#: The five facets, in evaluation order. Order is semantic, not cosmetic:
#: assumptions gate everything, invariants are sampled before the substantive
#: checks and again after, and outputs are meaningless if constraints failed.
FACETS = ("assumptions", "inputs", "constraints", "invariants", "outputs")

#: Facets whose failure means "could not determine" rather than "claim is false".
GATING_FACETS = ("assumptions", "inputs")

#: The kinds of artifact a verifier can be attached to.
VERIFIABLE_KINDS = ("skill", "capability", "agent", "memory")

#: Outcomes. ``error`` means the verifier itself raised — a bug in the check,
#: deliberately distinct from ``fail``, which means the check ran and the claim
#: did not hold. Conflating them hides broken verifiers inside real failures.
STATUSES = ("pass", "fail", "inconclusive", "error")

