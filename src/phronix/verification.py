# Running
# ---------------------------------------------------------------------------

def _evaluate(spec: Dict[str, Any], module: Any,
              context: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """Evaluate a spec's five facets in order and aggregate the verdict.

    The order encodes the semantics:

    1. **assumptions** gate everything. If a precondition does not hold, nothing
       downstream is evidence, so stop and report ``inconclusive``.
    2. **inputs** resolve into the context every later check receives. A missing
       required input is also a "cannot determine", not a failed claim.
    3. **invariants** are sampled BEFORE the substantive work.
    4. **constraints** are the claim itself.
    5. **outputs** are what must have been produced.
    6. **invariants** are sampled again and compared. A change means the act of
       verifying altered the thing being verified, which invalidates the run
       regardless of what the constraints said.
    """
    ctx: Dict[str, Any] = dict(context or {})
    facets: Dict[str, List[Dict[str, Any]]] = {facet: [] for facet in FACETS}

    # 1. Assumptions
    for entry in spec.get("assumptions") or []:
        facets["assumptions"].append(_run_check(entry, "check", ctx))
    unmet = [r for r in facets["assumptions"] if not r["ok"]]
    if unmet:
        return {
            "status": "inconclusive", "facets": facets,
            "evidence": "unmet assumptions: "
                        + "; ".join(f"{r['name']} ({r['evidence'] or r['detail']})"
                                    for r in unmet),
        }

    # 2. Inputs
    for entry in spec.get("inputs") or []:
        record = {"name": str(entry.get("name", "?")),
                  "detail": str(entry.get("detail", "")),
                  "required": bool(entry.get("required", True))}
        try:
            value = entry["resolve"](ctx)
        except Exception as exc:
            facets["inputs"].append({**record, "ok": False, "errored": True,
                                     "evidence": f"{type(exc).__name__}: {exc}"})
            continue
        resolved = value is not None
        if resolved:
            ctx[record["name"]] = value
        facets["inputs"].append({**record, "ok": resolved or not record["required"],
                                 "resolved": resolved,
                                 "evidence": "" if resolved else "did not resolve"})
    missing = [r for r in facets["inputs"] if not r["ok"]]
    if missing:
        return {
            "status": "inconclusive", "facets": facets,
            "evidence": "unresolved required inputs: "
                        + "; ".join(r["name"] for r in missing),
        }

    # 3. Invariants — before
    before: Dict[str, Any] = {}
    for entry in spec.get("invariants") or []:
        name = str(entry.get("name", "?"))
        try:
            before[name] = entry["sample"](ctx)
        except Exception as exc:
            before[name] = RuntimeError(f"{type(exc).__name__}: {exc}")

    # 4. Constraints
    for entry in spec.get("constraints") or []:
        facets["constraints"].append(_run_check(entry, "check", ctx))

    # 5. Outputs
    for entry in spec.get("outputs") or []:
        facets["outputs"].append(_run_check(entry, "check", ctx))

    # 6. Invariants — after, compared
    for entry in spec.get("invariants") or []:
        name = str(entry.get("name", "?"))
        record = {"name": name, "detail": str(entry.get("detail", ""))}
        prior = before.get(name)
        if isinstance(prior, RuntimeError):
            facets["invariants"].append({**record, "ok": False, "errored": True,
                                         "evidence": f"pre-sample failed: {prior}"})
            continue
        try:
            after = entry["sample"](ctx)
        except Exception as exc:
            facets["invariants"].append({**record, "ok": False, "errored": True,
                                         "evidence": f"post-sample failed: "
                                                     f"{type(exc).__name__}: {exc}"})
            continue
        held = prior == after
        facets["invariants"].append({
            **record, "ok": held,
            "evidence": "" if held else
                        f"changed during verification: {prior!r} -> {after!r}",
        })

    # Optional free-form check, folded in as a constraint so it cannot be
    # overlooked in the aggregate.
    extra = getattr(module, ENTRY_POINT, None)
    if callable(extra):
        try:
            raw = extra(ctx)
        except TypeError:
            raw = extra()
        except Exception as exc:
            raw = {"status": "fail", "evidence": f"{type(exc).__name__}: {exc}"}
        if isinstance(raw, dict) and raw.get("status"):
            status = str(raw["status"]).lower()
            facets["constraints"].append({
                "name": f"{ENTRY_POINT}()", "detail": "free-form check",
                "ok": status == "pass", "inconclusive": status == "inconclusive",
                "evidence": str(raw.get("evidence", "")),
            })

    failed = [
        (facet, record)
        for facet in ("constraints", "invariants", "outputs")
        for record in facets[facet]
        if not record["ok"] and not record.get("inconclusive")
    ]
    if failed:
        return {
            "status": "fail", "facets": facets,
            "evidence": "; ".join(
                f"{facet}.{r['name']}: {r['evidence'] or r['detail'] or 'did not hold'}"
                for facet, r in failed),
        }
    counted = sum(len(facets[f]) for f in FACETS)
    return {"status": "pass", "facets": facets,
            "evidence": f"all {counted} facet checks held"}


def _results_path() -> Path:
    from phronix.knowledge_graph import cache_root

    path = cache_root() / "verification"
    path.mkdir(parents=True, exist_ok=True)
    return path / "last-run.json"


def _record(results: List[Dict[str, Any]]) -> None:
    """Persist the last outcome per check.

    Kept in the cache, not in a layer: a run result is an observation about *this
    machine at this moment*, not knowledge to be shared. Committing it would make
    every run a diff, and a green result from someone else's laptop is not
    evidence about yours.
    """
    try:
        path = _results_path()
        stored = json.loads(path.read_text()) if path.exists() else {}
        if not isinstance(stored, dict):
            stored = {}
        for result in results:
            stored[result["name"]] = {
                "status": result["status"], "at": result["at"],
                "kind": result.get("kind", ""), "target": result.get("target", ""),
                "source": result.get("source", ""),
            }
        path.write_text(json.dumps(stored, indent=2) + "\n")
    except Exception:
        pass  # recording is diagnostics; never fail a run over it


def last_results() -> Dict[str, Any]:
    try:
        path = _results_path()
        return json.loads(path.read_text()) if path.exists() else {}
    except Exception:
        return {}


def run(
    name: str = "",
    kind: str = "",
    target: str = "",
    context: Optional[Dict[str, Any]] = None,
    include_builtin: bool = True,
) -> Dict[str, Any]:
    """Run the correctors — built-in structural ones and authored spec verifiers.

    With no arguments, everything runs. Filters combine: ``kind="skill"`` corrects
    every skill; ``target="software-postgres"`` corrects that one artifact.

    ``include_builtin=False`` restricts the run to authored verifiers. Useful when
    iterating on one spec; never the right setting for a completeness check, since
    the built-in correctors are the only ones with total coverage.
    """
    stamp = time.strftime("%Y-%m-%dT%H:%M:%S")
    results: List[Dict[str, Any]] = []

    if include_builtin and not name:
        from phronix.correctors import correct_all

        for outcome in correct_all(kind):
            if target and outcome["target"] != target:
                continue
            results.append({
                "name": f"builtin:{outcome['kind']}:{outcome['target']}",
                "source": "builtin", "kind": outcome["kind"], "target": outcome["target"],
                "claim": "structurally well-formed and internally consistent",
                "status": outcome["status"], "evidence": outcome["evidence"],
                "findings": outcome["findings"], "checks_run": outcome["checks_run"],
                "at": stamp,
            })

    for entry in discover():
        if name and entry["name"] != name:
            continue
        if kind and entry.get("kind") != kind:
            continue
        if target and entry.get("target") != target:
            continue

        record = {"name": entry["name"], "source": "authored",
                  "kind": entry.get("kind", ""), "target": entry.get("target", ""),
                  "claim": entry.get("claim", ""), "layer": entry.get("layer"),
                  "at": stamp}
        if entry.get("error"):
            results.append({**record, "status": "error", "evidence": entry["error"]})
            continue
        if entry.get("spec_problems"):
            results.append({**record, "status": "error",
                            "evidence": "malformed spec: " + "; ".join(entry["spec_problems"])})
            continue
        try:
            module = _load_module(Path(entry["file"]))
            outcome = _evaluate(getattr(module, SPEC_ATTR), module, context)
            results.append({**record, **outcome})
        except Exception as exc:
            results.append({**record, "status": "error",
                            "evidence": f"{type(exc).__name__}: {exc}",
                            "traceback": traceback.format_exc(limit=4)})

    if not results:
        return {"status": "no_verifiers", "results": [],
                "counts": {status: 0 for status in STATUSES},
                "summary": "no corrector matched"
                           + (f" (name={name!r})" if name else "")
                           + (f" (kind={kind!r})" if kind else "")
                           + (f" (target={target!r})" if target else "")}

    _record(results)
    counts = {status: sum(1 for r in results if r["status"] == status) for status in STATUSES}
    # Aggregation preserves the distinctions the individual results carry, because
    # collapsing them here would undo the whole point of keeping them apart:
    #
    #   fail          dominates — a claim recorded as true is demonstrably false.
    #   error         next — the checks themselves are broken, which is worse than
    #                 missing checks but is NOT a finding about the claim.
    #   inconclusive  only when nothing passed; it is never a failure on its own,
    #                 and treating it as one trains people to ignore the signal.
    if counts["fail"]:
        overall = "fail"
    elif counts["error"]:
        overall = "error"
    elif counts["inconclusive"] and not counts["pass"]:
        overall = "inconclusive"
    else:
        overall = "pass"
    return {
        "status": overall, "counts": counts, "results": results,
        "summary": (f"{counts['pass']} passed, {counts['fail']} failed, "
                    f"{counts['inconclusive']} inconclusive, {counts['error']} errored"),
    }


