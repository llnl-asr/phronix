def _load_module(path: Path):
    """Import a verifier module without leaving bytecode in the user's repository.

    Verifiers live inside a project's committed ``.phronix/`` tree, so a normal
    import drops a ``__pycache__`` directory there — untracked churn in a
    directory whose whole purpose is to be reviewed and committed. Suppressing
    bytecode for the duration costs a few milliseconds per load and keeps the
    layer clean.
    """
    module_name = f"phronix_verifier_{path.stem}"
    spec = importlib.util.spec_from_file_location(module_name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot build an import spec for {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    previous = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        spec.loader.exec_module(module)
    except Exception:
        sys.modules.pop(module_name, None)
        raise
    finally:
        sys.dont_write_bytecode = previous
    return module


def validate(source: str, name: str) -> Optional[str]:
    """Return an error message if *source* is not a usable verifier, else ``None``."""
    try:
        compile(source, f"<verifier {name}>", "exec")
    except SyntaxError as exc:
        return f"syntax error at line {exc.lineno}: {exc.msg}"
    if not re.search(rf"(?m)^{SPEC_ATTR}\s*=", source):
        return (f"a verifier must define `{SPEC_ATTR} = {{...}}` with kind, target, claim "
                f"and the facets ({', '.join(FACETS)})")
    return None


def validate_spec(spec: Any) -> List[str]:
    """Structural problems with a loaded SPEC, as a list of messages.

    Checked at load time rather than at run time: a malformed facet discovered
    mid-run produces a partial verdict that looks like a result.
    """
    problems: List[str] = []
    if not isinstance(spec, dict):
        return [f"{SPEC_ATTR} must be a dict, got {type(spec).__name__}"]
    for key in ("kind", "target", "claim"):
        if not str(spec.get(key, "")).strip():
            problems.append(f"{SPEC_ATTR}['{key}'] is required")
    if spec.get("kind") and spec["kind"] not in VERIFIABLE_KINDS:
        problems.append(f"kind={spec['kind']!r} must be one of {'|'.join(VERIFIABLE_KINDS)}")

    for facet in FACETS:
        entries = spec.get(facet, [])
        if entries is None:
            continue
        if not isinstance(entries, (list, tuple)):
            problems.append(f"{facet} must be a list, got {type(entries).__name__}")
            continue
        for i, entry in enumerate(entries):
            if not isinstance(entry, dict):
                problems.append(f"{facet}[{i}] must be a dict")
                continue
            if not str(entry.get("name", "")).strip():
                problems.append(f"{facet}[{i}] needs a 'name'")
            required_key = "resolve" if facet == "inputs" else (
                "sample" if facet == "invariants" else "check")
            if not callable(entry.get(required_key)):
                problems.append(f"{facet}[{i}] ({entry.get('name', '?')}) needs a "
                                f"callable '{required_key}'")
    if not (spec.get("constraints") or spec.get("outputs")):
        problems.append(
            "a spec with no constraints and no outputs cannot fail, so it proves nothing — "
            "state at least one condition the claim asserts")
    return problems


