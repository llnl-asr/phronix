"""Sync tools: push learning out to the harnesses, and report the store's state.

Skills, agent templates and the permission policy are the source of truth. What
each harness actually reads is generated from them. These tools are the bridge —
call one after any self-learning edit, or the change exists in the store and is
invisible to the harness that needed it.
"""
from __future__ import annotations

import json
from typing import Any


def register(mcp: Any) -> None:
    @mcp.tool()
    def agents_sync(target_root: str = "") -> str:
        """Re-render every harness's agent files from the YAML templates.

        **Call this after ANY edit to an agent template or to
        ``common-sections.yaml``.** The files each harness reads —
        ``.claude/agents/*.md``, ``.opencode/agents/*.md``,
        ``.github/agents/*.agent.md``, ``.codex/agents/*.toml`` — are generated
        artifacts. Editing one directly is silently reverted by the next sync;
        edit the template instead.

        One-way and lossless: templates are the only source of truth, and
        rendered copies are never merged back.

        Args:
            target_root: workspace root (default: detected project root).

        Returns JSON: {status, changed, installed, conflicts, summary}. A conflict
        means a file of that name exists and was NOT generated by phronix; it is
        left untouched rather than overwritten.
        """
        from phronix.agents import sync_agents

        try:
            return json.dumps(sync_agents(target_root or None), indent=2)
        except Exception as exc:
            return json.dumps({"status": "error", "error": f"{type(exc).__name__}: {exc}"})

    @mcp.tool()
    def skills_sync(target_root: str = "") -> str:
        """Re-link every visible skill into the harness skill directories.

        Call this after creating a skill, so Claude Code and OpenCode discover it
        natively in this session rather than the next one. The ``skill_*`` tools
        see a new skill immediately regardless — they read the store directly —
        so this only matters for native discovery.

        Returns JSON: {status, changed, installed, conflicts}.
        """
        from phronix.skills import ensure_skills_setup

        try:
            return json.dumps(ensure_skills_setup(target_root or None), indent=2)
        except Exception as exc:
            return json.dumps({"status": "error", "error": f"{type(exc).__name__}: {exc}"})

    @mcp.tool()
    def permissions_sync(target_root: str = "") -> str:
        """Re-render the permission policy into each harness's dialect.

        Call this after editing ``workspace/permissions.yaml``, and after adding a
        capability — the MCP tool allowlist is discovered by scanning for
        registered tools, so a new capability is not pre-approved until this runs,
        and will otherwise interrupt an unattended session with a prompt.

        Returns JSON: {status, claude, opencode, copilot, codex, changed, summary}.
        """
        from phronix.permissions import sync_permissions

        try:
            return json.dumps(sync_permissions(target_root or None), indent=2)
        except Exception as exc:
            return json.dumps({"status": "error", "error": f"{type(exc).__name__}: {exc}"})

    @mcp.tool()
    def hooks_sync(target_root: str = "") -> str:
        """Re-render the prompt-injection hooks for every harness that supports one.

        Hooks are what inject relevant memory into the user's raw prompt — the one
        channel the MCP middleware cannot see. Rarely needed by hand; the server
        does it on start.

        Returns JSON: {status, claude, codex, opencode, copilot, advisories}.
        The advisories list what the USER must enable themselves, since a repo
        must not write to a global config.
        """
        from phronix.hooks import sync_hooks

        try:
            return json.dumps(sync_hooks(target_root or None), indent=2)
        except Exception as exc:
            return json.dumps({"status": "error", "error": f"{type(exc).__name__}: {exc}"})

    @mcp.tool()
    def phronix_status() -> str:
        """Report the state of the knowledge store: layers, counts, and write target.

        Call this when you are unsure where something lives or where a new lesson
        will land. The ``write_layer`` field is where ``skill_write``,
        ``memory_write`` and ``capability_new`` will persist by default, and
        therefore who will inherit what you record:

        - ``bundled`` — everyone who installs phronix (you are developing phronix
          itself, from a source checkout).
        - ``project`` — everyone who clones this repository.
        - ``user`` — only you, across your own projects.

        ``verification`` reports how much of the store has an executable check
        behind it. A low number means most of what this project "knows" is
        unfalsifiable — call ``verify_coverage()`` for the detail.

        Returns JSON: {status, layers, write_layer, verification, harness_models,
        version}.
        """
        from phronix import __version__
        from phronix.harness_models import summarize
        from phronix.layers import describe, resolve_write_layer

        try:
            write_layer = resolve_write_layer()
            target = {"name": write_layer.name, "root": str(write_layer.root),
                      "shared": write_layer.shared}
        except Exception as exc:
            target = {"error": f"{type(exc).__name__}: {exc}"}

        try:
            from phronix.verification import coverage

            report = coverage()
            verification = {k: report[k] for k in
                            ("total_artifacts", "covered", "uncovered", "percent",
                             "orphaned_verifiers", "never_run")}
        except Exception as exc:
            verification = {"error": f"{type(exc).__name__}: {exc}"}

        return json.dumps({
            "status": "ok",
            "version": __version__,
            "layers": describe(),
            "write_layer": target,
            "verification": verification,
            "harness_models": summarize(),
        }, indent=2)
